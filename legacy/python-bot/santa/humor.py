def easter_egg(text: str) -> str | None:
    low = (text or "").lower().strip()
    if low in ("🎅", "🎄", "❄️", "☃️"):
        return random.choice(SANTA_FACTS)
    for pattern, answers in EASTER_EGGS:
        if pattern.search(low):
            return random.choice(answers)
    return None
