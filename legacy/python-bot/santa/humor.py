def top_wishes(wishlists: list[str], limit: int = 5) -> list[str]:
    """Самые частые «запросы рынка» в вишлистах — слова от 4 букв."""
    words = Counter()
    for text in wishlists:
        seen = set()
        for w in re.findall(r"[а-яёa-z]{4,}", text.lower()):
            if w in _STOP or w in seen or w.startswith("http"):
                continue
            seen.add(w)
            words[w] += 1
    return [w for w, n in words.most_common(limit) if n >= 1]


def bar(share: float, width: int = 10) -> str:
    full = round(max(0.0, min(1.0, share)) * width)
    return "▰" * full + "▱" * (width - full)


