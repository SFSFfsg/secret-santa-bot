/** Популярные запросы в вишлистах. Слово попадает в отчёт, только если встречается у minPeople разных людей. */
export function topWishes(wishlists: string[], minPeople = 3, limit = 5): string[] {
  const counts = new Map<string, number>();
  for (const text of wishlists) {
    const seen = new Set<string>();
    for (const w of text.toLowerCase().match(/[а-яёa-z]{4,}/g) ?? []) {
      if (STOP.has(w) || seen.has(w) || w.startsWith("http")) continue;
      seen.add(w);
      counts.set(w, (counts.get(w) ?? 0) + 1);
    }
  }
  return [...counts.entries()]
    .filter(([, n]) => n >= minPeople)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, limit)
    .map(([w]) => w);
}

