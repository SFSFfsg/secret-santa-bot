export function easterEgg(text: string): string | null {
  const low = (text ?? "").toLowerCase().trim();
  if (["🎅", "🎄", "❄️", "☃️"].includes(low)) return pick(SANTA_FACTS);
  for (const [re, answers] of EGGS) if (re.test(low)) return pick(answers);
  return null;
}

export function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

